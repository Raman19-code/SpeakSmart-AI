import { useCallback, useEffect, useRef, useState } from "react";
import type { Category, Difficulty, Topic } from "../types";
import { CATEGORIES, DIFFICULTIES, pickFromBank } from "../data/topics";
import { useApp } from "../hooks/AppContext";
import { ApiClientError, generateTopics } from "../services/api";
import { ChoiceGroup } from "./ChoiceGroup";

interface Props {
  /** Receives "Title: prompt" for the chosen topic, or "" when nothing valid is chosen. */
  onChange: (topic: string, title: string) => void;
}

const asText = (t: Topic) => `${t.title}: ${t.prompt}`;

export function TopicChooser({ onChange }: Props) {
  const { capabilities } = useApp();
  const aiTopics = capabilities.status === "ready" && capabilities.caps.ai;

  const [category, setCategory] = useState<Category>("technology");
  const [difficulty, setDifficulty] = useState<Difficulty>("medium");
  const [topics, setTopics] = useState<Topic[]>(() => pickFromBank("technology", "medium"));
  const [source, setSource] = useState<"bank" | "ai">("bank");
  const [note, setNote] = useState("");
  const [loading, setLoading] = useState(false);
  const [selected, setSelected] = useState<string | null>(null);
  const [custom, setCustom] = useState("");
  const emit = useRef(onChange);
  emit.current = onChange;

  const choose = useCallback((t: Topic) => {
    setSelected(t.id);
    setCustom("");
    emit.current(asText(t), t.title);
  }, []);

  // Keep the parent in sync when the list is replaced.
  useEffect(() => {
    if (selected && !topics.some((t) => t.id === selected)) {
      setSelected(null);
      if (!custom.trim()) emit.current("", "");
    }
  }, [topics, selected, custom]);

  const suggest = async () => {
    setLoading(true);
    setNote("");
    try {
      if (aiTopics) {
        const res = await generateTopics(category, difficulty, 3);
        setTopics(res.topics);
        setSource("ai");
      } else {
        setTopics(pickFromBank(category, difficulty, 3));
        setSource("bank");
      }
    } catch (e) {
      setTopics(pickFromBank(category, difficulty, 3));
      setSource("bank");
      setNote(`AI topics failed (${(e as ApiClientError).message}) so built-in topics are shown instead.`);
    } finally {
      setLoading(false);
    }
  };

  const onCustom = (value: string) => {
    setCustom(value);
    setSelected(null);
    emit.current(value.trim(), value.trim());
  };

  return (
    <div className="space-y-5">
      <ChoiceGroup label="Category" options={CATEGORIES.map((c) => ({ value: c.id, label: c.label }))} value={category} onChange={setCategory} />
      <ChoiceGroup
        label="Difficulty"
        options={DIFFICULTIES.map((d) => ({ value: d.id, label: d.label, hint: d.hint }))}
        value={difficulty}
        onChange={setDifficulty}
      />
      <div className="flex flex-wrap items-center gap-3">
        <button type="button" className="btn btn-ghost" onClick={() => void suggest()} disabled={loading}>
          {loading ? "Finding topics…" : "Suggest topics"}
        </button>
        <span className="text-sm text-slate-400" role="status">
          {source === "ai" ? "Generated by AI for this request." : "From the built-in topic bank (written by hand, not AI)."}
        </span>
      </div>
      {note && (
        <p role="alert" className="rounded-lg bg-amber-400/10 px-3 py-2 text-sm text-amber-100">
          {note}
        </p>
      )}

      {topics.length === 0 ? (
        <p className="text-slate-400">No topics for that combination. Try another category.</p>
      ) : (
        <ul className="grid gap-3 md:grid-cols-3" aria-label="Suggested topics">
          {topics.map((t) => (
            <li key={t.id}>
              <button
                type="button"
                aria-pressed={selected === t.id}
                onClick={() => choose(t)}
                className={`card h-full w-full p-4 text-left transition-colors hover:bg-white/[0.07] ${
                  selected === t.id ? "!border-brand-400 bg-brand-500/15" : ""
                }`}
              >
                <span className="block font-semibold text-white">{t.title}</span>
                <span className="mt-1 block text-sm text-slate-300">{t.prompt}</span>
                <span className="mt-2 block text-xs capitalize text-slate-400">{t.difficulty}</span>
              </button>
            </li>
          ))}
        </ul>
      )}

      <div>
        <label htmlFor="custom-topic" className="mb-1 block text-sm font-medium text-slate-300">
          Or write your own topic
        </label>
        <input
          id="custom-topic"
          className="field"
          value={custom}
          maxLength={250}
          onChange={(e) => onCustom(e.target.value)}
          placeholder="e.g. Should my college offer more elective courses?"
        />
      </div>
    </div>
  );
}
